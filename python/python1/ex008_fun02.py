# plus(a, b)
def plus(a, b):
    return a+b
print('+  : ', plus(300, 200))

# minus
def minus(a, b):
    return a-b
print('-  : ', minus(300, 200))

# mult
def mult(a, b):
    return a*b
print('*  : ', mult(300, 200))

# div
def div(a, b):
    return a/b
print('/  : ', div(300, 200))
